using System.Globalization;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
namespace Group_06_NMB_Haematology_Diagnostic_Laboratory.Services;

public static class ManagementReportPdf
{
    public static byte[] Generate(string title, string criteria, string summary, string[] headings,
        IEnumerable<string[]> source, DateTimeOffset generatedAt, string generatedBy)
    {
        var rows = source.ToList();
        var generated = generatedAt.ToOffset(TimeSpan.FromHours(2)).ToString("dd MMM yyyy, HH:mm", CultureInfo.GetCultureInfo("en-ZA")) + " SAST";
        return Document.Create(document => document.Page(page => {
            page.Size(PageSizes.A4.Landscape()); page.Margin(32);
            page.DefaultTextStyle(x => x.FontSize(9).FontColor(Colors.Grey.Darken4));
            page.Header().PaddingBottom(14).Column(header => {
                header.Item().Text("NMB Haematology Diagnostic Laboratory").SemiBold();
                header.Item().PaddingTop(5).Text(title).FontSize(20).Bold();
                header.Item().PaddingTop(5).Text(criteria);
                header.Item().Text("Generated by: " + generatedBy).FontSize(8);
                header.Item().Text("Generated: " + generated).FontSize(8);
            });
            page.Content().Column(content => {
                content.Spacing(12);
                content.Item().ShowEntire().Background(Colors.Grey.Lighten4).Padding(10).Text(summary).Bold();
                if (rows.Count == 0)
                    content.Item().Text("No records found for the selected criteria.");
                else content.Item().Table(table => {
                    table.ColumnsDefinition(columns => {
                        for (var i = 0; i < headings.Length; i++) columns.RelativeColumn(i < 2 ? 2 : 1);
                    });
                    table.Header(header => {
                        foreach (var heading in headings)
                            header.Cell().Background(Colors.Grey.Lighten3).Padding(7).Text(heading).Bold();
                    });
                    foreach (var row in rows)
                        foreach (var value in row)
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(7).Text(value);
                });
            });
            page.Footer().PaddingTop(10).BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(5).Row(footer => {
                footer.RelativeItem().Text("NMB-HLabSys • Management report").FontSize(8);
                footer.AutoItem().Text(text => {
                    text.DefaultTextStyle(x => x.FontSize(8));
                    text.Span("Page "); text.CurrentPageNumber(); text.Span(" of "); text.TotalPages();
                });
            });
        })).GeneratePdf();
    }
}
