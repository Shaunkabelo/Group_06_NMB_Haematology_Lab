using System.Globalization;
using Group_06_NMB_Haematology_Diagnostic_Lab.Data.Models;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Group_06_NMB_Haematology_Diagnostic_Laboratory.Services;

public static class TestsPerformedPdf
{
    private static readonly CultureInfo Culture = CultureInfo.GetCultureInfo("en-ZA");
    public static byte[] Generate(IEnumerable<TestsPerformedDetail> source, DateTime start,
        DateTime end, DateTimeOffset generatedAt, string generatedBy, IEnumerable<TestType> testTypes)
    {
        var rows = source.OrderBy(x => x.CategoryName, StringComparer.OrdinalIgnoreCase)
            .ThenBy(x => x.TestName, StringComparer.OrdinalIgnoreCase)
            .ThenBy(x => x.CompletionDateTime).ToList();
        var total = rows.Count;
        var dailyVolumes = TestReportInsights.DailyVolumes(rows);
        var consumableUsage = TestReportInsights.EstimatedConsumableUsage(rows, testTypes);
        string Number(long value) => value.ToString("N0", Culture);
        var timestamp = generatedAt.ToOffset(TimeSpan.FromHours(2)).ToString("dd MMM yyyy, HH:mm", Culture) + " SAST";
        return Document.Create(document => document.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(36);
            page.DefaultTextStyle(x => x.FontSize(10).FontColor(Colors.Grey.Darken4));
            page.Header().PaddingBottom(14).Column(header =>
            {
                header.Item().Text("NMB Haematology Diagnostic Laboratory").FontSize(10).SemiBold();
                header.Item().PaddingTop(5).Text("Laboratory Test Activity Report").FontSize(20).Bold();
                header.Item().Text("Completed tests, daily activity and estimated configured consumable usage").FontSize(10).Italic();
                header.Item().PaddingTop(5).Text(
                    $"Reporting period: {start.ToString("dd MMM yyyy", Culture)} – {end.ToString("dd MMM yyyy", Culture)} (inclusive)");
                header.Item().Text($"Generated by: {generatedBy}").FontSize(9);
                header.Item().Text($"Generated: {timestamp}").FontSize(9);
            });
            page.Content().Column(content =>
            {
                content.Spacing(12);
                content.Item().ShowEntire().Background(Colors.Grey.Lighten4).Padding(12).Column(summary =>
                {
                    summary.Item().Text("Summary").FontSize(12).Bold();
                    summary.Item().Text($"Total tests performed: {Number(total)}");
                    summary.Item().Text($"Categories with completed tests: {Number(rows.Select(x => x.CategoryName).Distinct(StringComparer.OrdinalIgnoreCase).Count())}");
                    summary.Item().Text($"Days with completed tests: {Number(dailyVolumes.Count)}");
                });
                content.Item().ShowEntire().Column(criteria =>
                {
                    criteria.Item().Text("Scope and criteria").Bold();
                    criteria.Item().Text("Lists every completed laboratory test using its recorded completion date. Historical tests remain included when a category is inactive.");
                    criteria.Item().PaddingTop(4).Text("Rows are grouped by category, then ordered by test name and completion date.").FontSize(9);
                });
                if (rows.Count == 0)
                {
                    content.Item().ShowEntire().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(16)
                        .Text("No records found for the selected date range.");
                }
                else
                {
                    content.Item().ShowEntire().Column(daily =>
                    {
                        daily.Item().Text("Tests completed per date").FontSize(12).Bold();
                        daily.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns => { columns.RelativeColumn(2); columns.RelativeColumn(); });
                            table.Header(header =>
                            {
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(6).Text("Completion date").Bold();
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(6).Text("Tests completed").Bold();
                            });
                            foreach (var day in dailyVolumes)
                            {
                                table.Cell().Padding(6).Text(day.Date.ToString("dd MMM yyyy", Culture));
                                table.Cell().Padding(6).Text(Number(day.TestsCompleted));
                            }
                        });
                    });
                    foreach (var category in rows.GroupBy(row => row.CategoryName, StringComparer.OrdinalIgnoreCase))
                    {
                        content.Item().ShowEntire().Column(group =>
                        {
                            group.Item().Background(Colors.Grey.Lighten3).Padding(8)
                                .Text($"Category: {category.Key}").Bold();
                            foreach (var test in category)
                            {
                                group.Item().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(8).Row(row =>
                                {
                                    row.RelativeItem().Text(test.TestName);
                                    row.AutoItem().Text(test.CompletionDateTime?.ToString("dd MMM yyyy", Culture) ?? "Not recorded");
                                });
                            }
                        });
                    }
                    content.Item().ShowEntire().PaddingTop(4).Column(consumables =>
                    {
                        consumables.Item().Text("Estimated consumables used").FontSize(12).Bold();
                        consumables.Item().Text("Estimate based on the current consumable quantity configured for each completed test type; it is not a stock-transaction audit.").FontSize(8).Italic();
                        if (consumableUsage.Count == 0)
                        {
                            consumables.Item().PaddingTop(5).Text("No configured consumable requirements were available for the completed tests.");
                            return;
                        }
                        consumables.Item().PaddingTop(5).Table(table =>
                        {
                            table.ColumnsDefinition(columns => { columns.RelativeColumn(2); columns.RelativeColumn(); columns.RelativeColumn(); });
                            table.Header(header =>
                            {
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(6).Text("Consumable").Bold();
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(6).Text("Estimated units used").Bold();
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(6).Text("Tests contributing").Bold();
                            });
                            foreach (var item in consumableUsage)
                            {
                                table.Cell().Padding(6).Text(item.ConsumableName);
                                table.Cell().Padding(6).Text(Number(item.EstimatedUnitsUsed));
                                table.Cell().Padding(6).Text(Number(item.TestsContributing));
                            }
                        });
                    });
                    content.Item().ShowEntire().AlignRight().Text($"Grand total: {Number(total)} tests").Bold();
                }
            });
            page.Footer().PaddingTop(12).BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(6).Row(footer =>
            {
                footer.RelativeItem().Text("NMB-HLabSys • Management report").FontSize(8);
                footer.AutoItem().Text(text =>
                {
                    text.DefaultTextStyle(x => x.FontSize(8));
                    text.Span("Page "); text.CurrentPageNumber(); text.Span(" of "); text.TotalPages();
                });
            });
        })).GeneratePdf();
    }
}
